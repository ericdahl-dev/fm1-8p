/*
 * make ui-golden: writes tests/ui_format_golden.h, every param's display walk (tests/ui_format_walk.h)
 * as it reads now, to stdout. The Makefile diffs it against the committed one, so the readable rows
 * that moved show, then puts it in place.
 *
 * With --dump it prints every value walked instead, one "name value<TAB>text" line each:
 * tools/ui_golden_diff.sh compares two trees' dumps (make ui-golden BASE=<commit>).
 */
#include <stdio.h>
#include "ui_format_walk.h"

static void put_c_string(const char *s)
{
    putchar('"');
    for (; *s; s++) {
        if (*s == '"' || *s == '\\')
            putchar('\\');
        putchar(*s);
    }
    putchar('"');
}

/* every value of every param's walk, one line each */
static int dump(void)
{
    uint32_t i;
    for (i = 0; i < FM_PARAM_COUNT; i++) {
        const fm_param_info *in = fm_param_info_get((uint16_t)i);
        int32_t v;
        if (!in)
            return 1;
        for (v = in->min - 2; v <= in->max + 2; v++) {
            char t[UFW_TEXT];
            ufw_text((uint16_t)i, v, t);
            printf("%s %ld\t%s\n", in->name, (long)v, t);
        }
    }
    return 0;
}

int main(int argc, char **argv)
{
    uint32_t i, k;
    int pad;
    if (argc > 1 && strcmp(argv[1], "--dump") == 0)
        return dump();
    printf("/* The screen's value text for every param, pinned (#196). GENERATED by make ui-golden from\n"
           " * tests/ui_format_walk.h: edit the display, then make it again and review the rows that moved.\n"
           " * Each param: its id, name, the values walked (min - 2 .. max + 2), their hash, then the text at\n"
           " * its min, 1/8 .. 7/8 of the way, max and default, as \"focus row | knob column\". */\n");
    printf("#define UFW_GOLDEN_N %uu\n", (unsigned)FM_PARAM_COUNT);
    printf("static const ufw_row UFW_GOLDEN[UFW_GOLDEN_N] = {\n");
    for (i = 0; i < FM_PARAM_COUNT; i++) {
        const fm_param_info *in = fm_param_info_get((uint16_t)i);
        uint32_t points, h;
        if (!in) {
            fprintf(stderr, "ui-golden: param %u has no info\n", (unsigned)i);
            return 1;
        }
        h = ufw_hash((uint16_t)i, &points);
        printf("    {%u, \"%s\", %uu, 0x%08lXu, {\n", (unsigned)i, in->name, (unsigned)points, (unsigned long)h);
        for (k = 0; k < UFW_SAMPLES; k++) {
            char t[UFW_TEXT];
            int32_t v = ufw_sample_value(in, k);
            ufw_text((uint16_t)i, v, t);
            printf("        ");
            put_c_string(t);
            pad = 24 - (int)strlen(t);
            printf(",%*s/* %s %ld%s */\n", pad > 1 ? pad : 1, "", in->name, (long)v,
                   k == UFW_SAMPLES - 1u ? ", the default" : "");
        }
        printf("    }},\n");
    }
    printf("};\n");
    return 0;
}
