"""VCF FREQ's cutoff curve, written once (#344).

    cents(K) = A2 K^2 + A1 K + A0, from MIDI note 0, K being VCF FREQ in knob steps (0..127, or a
    knob-step sum, fractional)

Fitted so the engine's resonant peak lands on PG-8X 2.0.13's (#130): the filter sweep of 2026-11-11,
VCF RES 96-127, noise in, no key follow, C4; within 0.45 semitone over VCF FREQ 48..112. PG-8X adds
VCF ENV and VCF KEY to VCF FREQ in knob steps, then plays the sum through this curve (#253).

tools/jx8p.py plays the curve (cutoff_cents) and generates engine/cutoff_curve.h from it (`make
generate`), which engine/filter.c includes. The engine adds its cutoff sources in linear cents, A1 of
them a knob step, from A0 at step 0, and bends the sum once onto the curve:
C(u) = u + A (u - A0)^2, A = A2 / A1^2.
"""
from fractions import Fraction

# The coefficients as decimal strings, so the header carries them exactly
A2 = "0.0988"
A1 = "115.03"
A0 = "-1474"


def cents(k):
    """The curve at k knob steps, in cents from MIDI note 0 (unrounded, unclamped)."""
    return float(A2) * k * k + float(A1) * k + float(A0)


def cents_per_step():
    """Linear cents a knob step: the curve's linear coefficient."""
    return float(A1)


def zero():
    """Linear cents at knob step 0: the curve's constant, an integer."""
    a0 = Fraction(A0)
    if a0.denominator != 1:
        raise ValueError("A0 must be a whole number of cents: %s" % A0)
    return int(a0)


def a_q32():
    """A = A2 / A1^2 in Q32, rounded to nearest."""
    return round(Fraction(A2) / Fraction(A1) ** 2 * 2 ** 32)


def emit_h():
    """engine/cutoff_curve.h: the curve's constants for the engine and its tests."""
    a2, a1 = Fraction(A2), Fraction(A1)
    q = a_q32()
    return "\n".join([
        "/* VCF FREQ's cutoff curve (#253, #344). Generated by tools/jx8p.py from",
        " * tools/cutoff_curve.py: do not edit, run `make generate`.",
        " *",
        " * cents(K) = %s K^2 + %s K %s %s, K in knob steps. The engine adds its" % (
            A2, A1, "-" if zero() < 0 else "+", abs(zero())),
        " * cutoff sources in linear cents, then bends the sum once onto the curve:",
        " * C(u) = u + A (u - FM_CURVE_ZERO)^2, A = A2 / A1^2 (engine/filter.c). */",
        "#ifndef FM1_8P_CUTOFF_CURVE_H",
        "#define FM1_8P_CUTOFF_CURVE_H",
        "",
        "#define FM_CURVE_ZERO (%d)  /* linear cents at knob step 0 */" % zero(),
        "#define FM_CURVE_A_Q32 %du  /* A2 / A1^2 in Q32 */" % q,
        "#define FM_CURVE_A_Q32_HALF %du  /* the inverse's rounding term */" % (q // 2),
        "",
        "/* The coefficients as exact fractions, for the tests' floating-point model */",
        "#define FM_CURVE_A2_NUM %d" % a2.numerator,
        "#define FM_CURVE_A2_DEN %d" % a2.denominator,
        "#define FM_CURVE_A1_NUM %d" % a1.numerator,
        "#define FM_CURVE_A1_DEN %d" % a1.denominator,
        "",
        "#endif",
        ""])
